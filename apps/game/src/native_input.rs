/// Keep platform types at the application boundary; engine-core stays headless.
pub(crate) fn keyboard_key(key: PhysicalKey) -> Option<Key> {
	match key {
		PhysicalKey::Code(code) => key_code(code),
		PhysicalKey::Unidentified(code) => Some(Key::Unidentified(match code {
			WindowNativeKeyCode::Unidentified => NativeKeyCode::Unidentified,
			WindowNativeKeyCode::Android(code) => NativeKeyCode::Android(code),
			WindowNativeKeyCode::MacOS(code) => NativeKeyCode::MacOS(code),
			WindowNativeKeyCode::Windows(code) => NativeKeyCode::Windows(code),
			WindowNativeKeyCode::Xkb(code) => NativeKeyCode::Xkb(code),
		})),
	}
}

