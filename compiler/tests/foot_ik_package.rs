// Generated by integrations/blender/build_character_fixture.py with --leg-ik in Blender 4.0.2.
const CHARACTER: &[u8] = include_bytes!("fixtures/foot-ik/character-fixture.glb");
const REEXPORTED: &[u8] = include_bytes!("fixtures/foot-ik/character-fixture-revised.glb");
const STEP: f64 = 1.0 / 60.0;
const ACTOR: &str = "actor";

struct Fixture(PathBuf);
impl Fixture {
	fn new() -> Self {
		let path = Path::new(env!("CARGO_MANIFEST_DIR"))
			.join("../target")
			.join(format!("qa-foot-ik-{}", AssetId::generate().as_str()));
		fs::create_dir_all(path.join("assets/scenes")).unwrap();
		Self(path)
	}
}
impl Drop for Fixture {
	fn drop(&mut self) {
		let _ = fs::remove_dir_all(&self.0);
	}
}

#[test]
fn foot_ik_tracks_a_step_in_editor_play_and_the_packaged_game_after_reexport() {
	let fixture = Fixture::new();
	let assets = fixture.0.join("assets");
	let initial = bridge::animation_asset::decode(CHARACTER).unwrap();
	let reexport = bridge::animation_asset::decode(REEXPORTED).unwrap();
	reexport.require_compatible_character(&initial).unwrap();
	let model = AssetId::generate();
	let graph_id = AssetId::generate();
	let source = initial.source_ref(model.clone());
	let foot_joint = source
		.character
		.as_ref()
		.unwrap()
		.joints
		.iter()
		.find_map(|(node, id)| {
			initial
				.nodes
				.iter()
				.any(|joint| joint.source_node == *node && joint.name.as_deref() == Some("Foot"))
				.then(|| id.clone())
		})
		.unwrap();
	let revised_ankle = reexport.joint_node(&foot_joint).unwrap();
	assert_eq!(
		reexport.nodes[usize::from(revised_ankle)].name.as_deref(),
		Some("Foot Revised")
	);
	let scene = scene_with_step(
		AnimatorSettings {
			asset_id: graph_id.clone(),
			binding: AnimatorBinding::Imported {
				source: source.clone(),
			},
			root_motion_source_node: None,
			foot_ik: Some(FootIkSettings {
				foot_joint: foot_joint.clone(),
				reach_mm: 250,
				sole_offset_mm: 200,
			}),
		},
		&model,
	);
	let mut project =
		ProjectData::for_scene("Foot IK Fixture", "scenes/main.json", &scene).unwrap();
	project.add_behavior(BehaviorSpec::ControlledMove {
		entity: key(ACTOR),
		speed: 1.2,
		space: BehaviorSpace::World,
	});
	let graph = AnimatorGraph {
		schema_version: 1,
		entry: "idle".into(),
		parameters: vec![],
		transitions: vec![],
		layout: Default::default(),
		states: vec![AnimatorState {
			id: "idle".into(),
			name: "Idle".into(),
			looping: true,
			clip: AnimationClipRef::Imported {
				source,
				clip_index: 0,
			},
		}],
	};
	let graph_bytes = graph.to_json().unwrap();
	let mut character = record(model.clone(), "character.glb", AssetKind::Model, CHARACTER);
	character.meshes.push(MeshSignature {
		index: 0,
		name: "Fixture Character".into(),
		primitives: 1,
		identity: None,
	});
	let mut animator = record(
		graph_id,
		"leg.animator.json",
		AssetKind::AnimatorGraph,
		&graph_bytes,
	);
	animator.dependencies.push(model);
	let mut catalog = AssetCatalog {
		assets: vec![character.clone(), animator],
		..Default::default()
	};
	fs::write(assets.join("leg.animator.json"), graph_bytes).unwrap();
	let scene_path = assets.join("scenes/main.json");
	fs::write(&scene_path, scene.to_json().unwrap()).unwrap();
	publish_character(&assets, &catalog, CHARACTER);
	let initial_trace = editor_trace(&assets, &project, reopen(&scene_path), &foot_joint);
	check_step(&initial_trace);

	character.fingerprint = fingerprint(REEXPORTED);
	character.bytes = REEXPORTED.len() as u64;
	character.revision += 1;
	catalog.replace(character).unwrap();
	publish_character(&assets, &catalog, REEXPORTED);
	let editor = editor_trace(&assets, &project, reopen(&scene_path), &foot_joint);
	check_step(&editor);
	assert_eq!(reopen(&scene_path), scene);

	let prepared = compiler::prepare_project(&project, &assets).unwrap();
	let staged = compiler::stage_prepared_project(&prepared, fixture.0.to_str().unwrap()).unwrap();
	let root = staged.path().join("assets");
	let installed = reopen(&root.join("scenes/main.json"));
	let packaged_project =
		ProjectData::from_json(&fs::read_to_string(staged.path().join("project.json")).unwrap())
			.unwrap();
	assert_eq!(fs::read(root.join("character.glb")).unwrap(), REEXPORTED);
	let mut player = GameSession::with_factory_for_scene(
		Arc::new(packaged_project),
		project.startup_scene_id.clone(),
		Arc::new(installed),
		Arc::new(ConfiguredBehaviorFactory),
	)
		.unwrap();
	player.set_animator_resolver(resolver(&root)).unwrap();
	player
		.active_mut()
		.set_controlled_input([1., 0., 0.])
		.unwrap();
	let game = (0..30)
		.map(|_| {
			player.tick(STEP).unwrap();
			height(player.active(), &foot_joint)
		})
		.collect::<Vec<_>>();
	assert_eq!(editor, game);
}

fn key(value: &str) -> EntityKey {
	EntityKey::new(value).unwrap()
}

fn scene_with_step(settings: AnimatorSettings, model: &AssetId) -> SceneData {
	let camera = Camera::default();
	let mut actor = EntityData::new(key(ACTOR), "Character", "character.glb")
		.with_asset_id(Some(model.clone()))
		.with_transform(TransformData {
			position: [-0.3, 0., 0.],
			..Default::default()
		});
	actor.animator = Some(Box::new(AnimatorComponent {
		id: ComponentId::new("animator").unwrap(),
		enabled: true,
		settings,
	}));
	let support = |name: &str, position, half_extents| {
		EntityData::new(key(name), name, "character.glb")
			.with_renderable(false)
			.with_transform(TransformData {
				position,
				..Default::default()
			})
			.with_collider(Some(ColliderData::Box {
				half_extents,
				offset: [0.; 3],
				interaction: Default::default(),
			}))
	};
	SceneData {
		schema_version: CURRENT_SCHEMA_VERSION,
		organization: Default::default(),
		default_game_camera: None,
		bindings: Default::default(),
		environment: Default::default(),
		lights: vec![],
		entities: vec![
			actor,
			support("floor", [0., -0.5, 0.], [5., 0.5, 5.]),
			support("step", [0.5, 0.09, 0.], [0.5, 0.09, 1.]),
		],
		camera: CameraData {
			follow: None,
			orbit: None,
			position: camera.position,
			yaw: camera.yaw,
			pitch: camera.pitch,
			vertical_fov: camera.vertical_fov,
			near_plane: camera.near,
			far_plane: camera.far,
		},
	}
}

fn editor_trace(root: &Path, project: &ProjectData, scene: SceneData, foot: &str) -> Vec<f32> {
	let mut editor = EditorSession::for_project(scene.clone(), project.clone()).unwrap();
	editor.set_animator_resolver(resolver(root)).unwrap();
	for command in [
		EditorCommandDto::StartPlay,
		EditorCommandDto::SetEntityInput {
			entity: ACTOR.into(),
			movement: [1., 0., 0.],
		},
	] {
		editor
			.execute_command(EditorCommandRequest {
				expected_revision: editor.revision(),
				command,
			})
			.unwrap();
	}
	let trace = (0..30)
		.map(|_| {
			editor.tick(STEP).unwrap();
			let pose = editor.animations().unwrap().pose(&key(ACTOR)).unwrap();
			let foot = pose.asset.joint_node(foot).unwrap();
			pose.globals[usize::from(foot)].w_axis.y
		})
		.collect();
	assert_eq!(*editor.authored_document(), scene);
	trace
}

fn height(player: &SimulationSession, foot: &str) -> f32 {
	let pose = player.animations().pose(&key(ACTOR)).unwrap();
	let foot = pose.asset.joint_node(foot).unwrap();
	pose.globals[usize::from(foot)].w_axis.y
}

fn check_step(trace: &[f32]) {
	assert!((trace[0] - 0.20).abs() < 0.001, "flat ground: {trace:?}");
	assert!((trace[29] - 0.38).abs() < 0.001, "on the step: {trace:?}");
}

fn resolver(root: &Path) -> AnimatorResolver {
	let root = root.to_path_buf();
	Arc::new(move |project, scene_id, scene| {
		bridge::animator_graph::prepare_scene(&root, project, scene_id, scene)
	})
}

fn reopen(path: &Path) -> SceneData {
	SceneData::from_json(&fs::read_to_string(path).unwrap()).unwrap()
}

fn publish_character(root: &Path, catalog: &AssetCatalog, bytes: &[u8]) {
	fs::write(root.join("character.glb"), bytes).unwrap();
	fs::write(root.join("asset-catalog.json"), catalog.to_json().unwrap()).unwrap();
}

fn record(id: AssetId, path: &str, kind: AssetKind, bytes: &[u8]) -> PersistentAsset {
	PersistentAsset {
		id,
		path: path.into(),
		kind,
		aliases: vec![],
		revision: 1,
		fingerprint: fingerprint(bytes),
		bytes: bytes.len() as u64,
		source_path: None,
		meshes: vec![],
		dependencies: vec![],
	}
}

fn fingerprint(bytes: &[u8]) -> String {
	format!("{:x}", Sha256::digest(bytes))
}
